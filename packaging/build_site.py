"""Copy the overlay's look into the website, so its live widgets are the real thing.

    uv run python packaging/build_site.py

Writes docs/hud/:
    hud.css     frontend/style.css with every selector scoped under .hud (body.x -> .hud.x,
                html/body page rules dropped), so it can't touch the rest of the page
    theme.css   frontend/theme.css as is (color variables on :root: the site uses them too)
    themes.js   frontend/themes.js (theme presets for the site's theme picker)
    track.json  the mock race's Monza outline (maps/0-Grand_Prix.json, all 1000 points)
Rerun after changing the overlay's CSS, themes or widget markup (capture_screenshots.py
runs it too).
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
OUT = ROOT / "docs" / "hud"
SCOPE = ".hud"


def _scope_selector(sel: str) -> str | None:
    sel = sel.strip()
    if not sel:
        return None
    if re.match(r"html\b", sel):
        return None  # page-level (html, body): the site owns those
    m = re.match(r"body(?![\w-])", sel)
    if m:
        rest = sel[m.end():]
        if not rest:
            return None  # plain body {}: page font / size, the site owns it
        return SCOPE + rest  # body.edit .x -> .hud.edit .x
    if sel == "*":
        return f"{SCOPE}, {SCOPE} *"
    return f"{SCOPE} {sel}"


def _blocks(css: str):
    """Top-level (prelude, body) pairs; comments removed."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            return
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < n:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        yield prelude, css[j + 1 : k - 1]
        i = k


def scope_css(css: str) -> str:
    out = []
    for prelude, body in _blocks(css):
        if prelude.startswith("@keyframes") or prelude.startswith("@font-face"):
            out.append(f"{prelude} {{{body}}}")
        elif prelude.startswith("@"):  # @media etc.: scope the rules inside
            out.append(f"{prelude} {{\n{scope_css(body)}\n}}")
        else:
            sels = [s for s in (_scope_selector(x) for x in prelude.split(",")) if s]
            if sels:
                out.append(f"{', '.join(sels)} {{{body}}}")
    return "\n".join(out)


def build() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    head = "/* generated by packaging/build_site.py from frontend/style.css: don't edit */\n"
    css = scope_css((FRONTEND / "style.css").read_text(encoding="utf-8"))
    (OUT / "hud.css").write_text(head + css + "\n", encoding="utf-8", newline="\n")
    for name in ("theme.css", "themes.js"):
        shutil.copy(FRONTEND / name, OUT / name)
    points = json.loads((ROOT / "maps" / "0-Grand_Prix.json").read_text())["points"]
    # full resolution, like the overlay (fewer points draw visibly chunkier corners)
    (OUT / "track.json").write_text(json.dumps(points, separators=(",", ":")), encoding="utf-8")
    print(f"  {OUT.relative_to(ROOT)}/: hud.css, theme.css, themes.js, track.json")


if __name__ == "__main__":
    build()
